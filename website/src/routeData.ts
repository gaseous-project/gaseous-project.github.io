import { defineRouteMiddleware } from '@astrojs/starlight/route-data';

export const onRequest = defineRouteMiddleware((context) => {
    const { locals } = context;
    const pathname = context.url.pathname;
    const sidebar = locals.starlightRoute.sidebar;

    // Determine what version path the user is visiting
    const isV1Route = pathname.includes('/v1/');
    const isV2Route = pathname.includes('/v2/');

    // Cleanly loop through and strip links belonging to the inactive version
    locals.starlightRoute.sidebar = sidebar.filter((entry) => {
        // 1. Safe-check: If this is an direct page link item
        if (entry.type === 'link') {
            if (isV1Route) return entry.href.includes('/v1/');
            if (isV2Route) return entry.href.includes('/v2/');
        }

        // 2. Safe-check: If this is a nested category group (Autogenerated structure)
        if (entry.type === 'group') {
            // Look inside the group to verify if any items belong to the active directory match
            const hasMatchingLinks = entry.entries.some((subEntry) => {
                if (subEntry.type === 'link') {
                    return isV1Route ? subEntry.href.includes('/v1/') : subEntry.href.includes('/v2/');
                }
                return false;
            });

            return hasMatchingLinks;
        }

        return true;
    });
});
